/** 按日期与命主生成当日签号（同一天同一人结果固定） */
export function qianIndex(dateKey, seed = '') {
  let h = 2166136261;
  for (const ch of dateKey + '|' + seed) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) % QIAN.length;
}
