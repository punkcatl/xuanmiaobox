/** 只取对象自身的键：地名来自分享链接 / 档案，可能是 constructor、__proto__ 等原型属性名 */
// 不用 Object.hasOwn：Safari 15.4 以下（Vite 默认构建目标 safari14 内）不支持且不会被转译
export const own = (obj, key) => (obj && Object.prototype.hasOwnProperty.call(obj, key) ? obj[key] : undefined);

/**
 * 查询出生地经度：优先区县级，其次市级。
 * @returns {{ longitude: number, level: 'district' | 'city' } | null}
 */

export function lookupLongitude(province, city, district) {
  const byDistrict = own(districtLongitudes, `${province}|${city}`);
  const d = district ? own(byDistrict, district) : undefined;
  if (typeof d === 'number') return { longitude: d, level: 'district' };
  const c = own(own(cityLongitudes, province), city);
  if (typeof c === 'number') return { longitude: c, level: 'city' };
  return null;
}
